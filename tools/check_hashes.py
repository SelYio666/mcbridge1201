"""Verify runs/SHA256SUMS.txt against the files on disk.

Usage:
  python tools/check_hashes.py [--manifest runs/SHA256SUMS.txt]

Exit 0 only when every listed path exists and matches its SHA-256. The manifest is
generated by tools/hash_evidence.py from working-tree bytes, so checkout filters
(CRLF) must not change the files between generation and checking.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=str(ROOT / "runs" / "SHA256SUMS.txt"))
    args = ap.parse_args()
    manifest = Path(args.manifest)
    if not manifest.exists():
        print(f"manifest not found: {manifest}", file=sys.stderr)
        return 2
    ok = mismatch = missing = 0
    for line in manifest.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        digest, sep, rel = line.partition("  ")
        if not sep or len(digest) != 64:
            print(f"BAD LINE: {line!r}", file=sys.stderr)
            mismatch += 1
            continue
        path = ROOT / rel
        if not path.exists():
            print(f"MISSING: {rel}", file=sys.stderr)
            missing += 1
            continue
        actual = sha256(path)
        if actual != digest:
            print(f"MISMATCH: {rel} expected {digest[:12]}… got {actual[:12]}…", file=sys.stderr)
            mismatch += 1
        else:
            ok += 1
    print(f"ok={ok} mismatch={mismatch} missing={missing}")
    return 0 if mismatch == 0 and missing == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
